function media_info(string $asset): array {
  if($asset==='snapshot-defacement'){
    $version='0';
    try{
      $q=db()->prepare("SELECT UNIX_TIMESTAMP(captured_at) ts, MD5(image_blob) image_hash FROM scenario_snapshots WHERE snapshot_key='defacement-final' LIMIT 1");
      $q->execute();
      $snap=$q->fetch();
      if($snap){
        $version=(string)($snap['ts']??'0').'-'.substr((string)($snap['image_hash']??''),0,12);
      }
    }catch(Throwable $e){}

    return [
      'src'=>'/snapshot.php?key=defacement-final&v='.rawurlencode($version),
      'fallback'=>'/assets/img/operations-room.svg',
      'caption'=>'Captura del portal de INTERAFAS con la pestaña clandestina // SYSTEM // visible.',
      'credit'=>'Captura del portal / Pulso Metropolitano',
      'source'=>''
    ];
  }

  if($asset==='snapshot-vuln20'){
    $version='0';
    try{
      $q=db()->prepare("SELECT UNIX_TIMESTAMP(captured_at) ts, MD5(image_blob) image_hash FROM scenario_snapshots WHERE snapshot_key='vuln20-final' LIMIT 1");
      $q->execute();
      $snap=$q->fetch();
      if($snap){
        $version=(string)($snap['ts']??'0').'-'.substr((string)($snap['image_hash']??''),0,12);
      }
    }catch(Throwable $e){}

    return [
      'src'=>'/snapshot.php?key=vuln20-final&v='.rawurlencode($version),
      'fallback'=>'/assets/img/operations-room.svg',
      'caption'=>'Evidencia visual preservada durante el estado crítico de la contingencia operacional.',
      'credit'=>'Evidencia operacional / Pulso Metropolitano',
      'source'=>''
    ];
  }

  $m=media_catalog();
  if(isset($m[$asset])) return $m[$asset];
  return ['src'=>'/assets/img/'.$asset,'fallback'=>'/assets/img/hero-water.svg','caption'=>'Imagen de archivo de Pulso Metropolitano.','credit'=>'Archivo / Pulso Metropolitano','source'=>''];
}
function article_time(array $a): string {
  $eventTimes=['FLAG_16'=>'09:12','FLAG_17'=>'10:44','FLAG_18'=>'12:31','FLAG_19'=>'14:18','FLAG_20'=>'16:47','VULN20_SNAPSHOT'=>'16:49','ALL_FLAGS'=>'17:06','RECOVERY_STARTED'=>'18:10'];
  if(!empty($a['event_required']) && isset($eventTimes[$a['event_required']])) return $eventTimes[$a['event_required']];
  $base=['0'=>'08:15','1'=>'09:08','2'=>'10:42','3'=>'12:18','4'=>'14:36','5'=>'18:10'];
  $ph=(string)($a['phase_required']??0); $delay=(int)($a['delay_seconds']??0);
  [$h,$m]=array_map('intval',explode(':',$base[$ph]??'08:15')); $m += intdiv($delay,60);
  $h += intdiv($m,60); $m%=60; return sprintf('%02d:%02d',$h%24,$m);
}
